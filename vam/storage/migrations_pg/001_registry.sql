-- E3: the registry read model (SQLite migrations 001-006) in PostgreSQL. Same tables, columns and
-- column order as the SQLite schema, so the registry code runs unchanged on either backend. Timestamps
-- stay epoch seconds (double precision) like the SQLite rows they are copied from.
CREATE TABLE videos (
 video_id text PRIMARY KEY, original_name text NOT NULL, source_path text NOT NULL,
 playback_path text, size_bytes bigint NOT NULL, duration double precision NOT NULL,
 created_at double precision NOT NULL, status text NOT NULL DEFAULT 'uploaded',
 active_generation text, model_fingerprint text, last_error text,
 source_sha256 text, transcript_generation text, transcript_status text NOT NULL DEFAULT 'not_started',
 transcript_error text, trashed_at double precision, published_seq bigint NOT NULL DEFAULT 0
);
CREATE TABLE index_jobs (
 job_id text PRIMARY KEY, video_id text NOT NULL REFERENCES videos(video_id) ON DELETE CASCADE,
 generation text NOT NULL, status text NOT NULL, phase text NOT NULL,
 current bigint NOT NULL DEFAULT 0, total bigint NOT NULL DEFAULT 0,
 attempt integer NOT NULL, logs text NOT NULL DEFAULT '[]', result text,
 error_code text, error text, started_at double precision NOT NULL, updated_at double precision NOT NULL,
 kind text NOT NULL DEFAULT 'video'
);
CREATE INDEX idx_jobs_video ON index_jobs(video_id, started_at);
CREATE UNIQUE INDEX idx_jobs_active ON index_jobs(video_id) WHERE status IN ('queued','running');
CREATE TABLE conversations (
 conversation_id text PRIMARY KEY,
 video_id text NOT NULL REFERENCES videos(video_id) ON DELETE CASCADE,
 created_at double precision NOT NULL, updated_at double precision NOT NULL,
 summary text NOT NULL DEFAULT '', summary_through bigint NOT NULL DEFAULT 0,
 summary_attempt_through bigint NOT NULL DEFAULT 0, summary_status text NOT NULL DEFAULT 'empty'
);
CREATE INDEX idx_conversations_video ON conversations(video_id, updated_at DESC);
CREATE TABLE conversation_requests (
 conversation_id text NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
 request_id text NOT NULL, payload text NOT NULL, original_text text NOT NULL,
 rewritten_question text, resolution text, status text NOT NULL,
 result text, error_code text, created_at double precision NOT NULL, updated_at double precision NOT NULL,
 owner text, lease_until double precision,
 PRIMARY KEY(conversation_id, request_id)
);
CREATE UNIQUE INDEX idx_conversation_active ON conversation_requests(conversation_id)
 WHERE status IN ('accepted','running');
CREATE INDEX idx_conversation_requests_active_lease ON conversation_requests(status, lease_until)
 WHERE status IN ('accepted','running');
CREATE TABLE messages (
 message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id text NOT NULL REFERENCES conversations(conversation_id) ON DELETE CASCADE,
 request_id text NOT NULL, role text NOT NULL CHECK (role IN ('user','assistant')),
 content text NOT NULL, created_at double precision NOT NULL,
 UNIQUE(conversation_id, request_id, role),
 FOREIGN KEY(conversation_id, request_id) REFERENCES conversation_requests(conversation_id, request_id) ON DELETE CASCADE
);
CREATE INDEX idx_messages_conversation ON messages(conversation_id, message_id);
CREATE TABLE study_jobs (
 job_id text PRIMARY KEY, video_id text NOT NULL REFERENCES videos(video_id) ON DELETE CASCADE,
 request_id text NOT NULL, options text NOT NULL, status text NOT NULL,
 phase text NOT NULL, current bigint NOT NULL DEFAULT 0, total bigint NOT NULL DEFAULT 0,
 artifact_id text, error_code text, created_at double precision NOT NULL, updated_at double precision NOT NULL,
 UNIQUE(video_id, request_id)
);
CREATE UNIQUE INDEX idx_study_active ON study_jobs(video_id) WHERE status IN ('queued','running');
CREATE TABLE study_artifacts (
 artifact_id text PRIMARY KEY, video_id text NOT NULL REFERENCES videos(video_id) ON DELETE CASCADE,
 job_id text NOT NULL REFERENCES study_jobs(job_id) ON DELETE CASCADE,
 source_versions text NOT NULL, content text NOT NULL, created_at double precision NOT NULL
);
CREATE INDEX idx_study_video ON study_artifacts(video_id, created_at DESC);
-- Published files of each publication (index generations, playback) as immutable objects; any instance
-- with a missing or new DATA_ROOT rebuilds its local copy from here (sha256-verified).
CREATE TABLE publication_objects (
 video_id text NOT NULL REFERENCES videos(video_id) ON DELETE CASCADE,
 relative_path text NOT NULL, object_key text NOT NULL, sha256 text NOT NULL, size_bytes bigint NOT NULL,
 published_seq bigint NOT NULL, created_at double precision NOT NULL,
 PRIMARY KEY(video_id, relative_path)
);
